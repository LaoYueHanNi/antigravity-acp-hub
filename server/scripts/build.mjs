import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const serverDir = resolve(__dirname, "..");
const repoRoot = resolve(serverDir, "..");

const uiEntry = resolve(serverDir, "ui", "dashboard.mjs");
const uiTemplatePath = resolve(serverDir, "ui", "dashboard.html");
const generatedHtmlModule = resolve(serverDir, "generated", "dashboard-html.mjs");
const entryPoint = resolve(serverDir, "index.mjs");
const outfile = resolve(repoRoot, "dist", "mcp-server.mjs");

// Phase 1: Bundle the MCP App browser script and inline it into a single self-contained HTML module.
const uiBuild = await build({
  entryPoints: [uiEntry],
  bundle: true,
  platform: "browser",
  target: ["es2022"],
  format: "esm",
  minify: true,
  sourcemap: false,
  write: false,
  legalComments: "none",
});

const bundledUiJs = uiBuild.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const templateHtml = readFileSync(uiTemplatePath, "utf8");
const placeholder = "/*__ACP_HUB_UI_JS__*/";
if (!templateHtml.includes(placeholder)) {
  throw new Error(`Dashboard template ${uiTemplatePath} is missing placeholder ${placeholder}`);
}
const finalHtml = templateHtml.replace(placeholder, () => bundledUiJs);

mkdirSync(dirname(generatedHtmlModule), { recursive: true });
writeFileSync(
  generatedHtmlModule,
  `// Auto-generated by server/scripts/build.mjs — do not edit manually.\nexport const DASHBOARD_HTML = ${JSON.stringify(finalHtml)};\n`,
  "utf8",
);

const htmlSizeKb = (Buffer.byteLength(finalHtml, "utf8") / 1024).toFixed(1);
console.log(
  `[build] Generated self-contained MCP App HTML module: ${generatedHtmlModule} (${htmlSizeKb} KB)`,
);

// Phase 2: Bundle the MCP server (with the inline dashboard HTML embedded) into a single file.
await build({
  entryPoints: [entryPoint],
  outfile,
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  minify: false,
  sourcemap: false,
  legalComments: "eof",
  banner: {
    js: [
      'import { createRequire as __acpHubCreateRequire } from "node:module";',
      "const require = __acpHubCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});

const sizeKb = (statSync(outfile).size / 1024).toFixed(1);
console.log(`[build] Generated self-contained MCP bundle: ${outfile} (${sizeKb} KB)`);
