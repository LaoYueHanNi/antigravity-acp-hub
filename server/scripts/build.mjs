import { mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const __dirname = dirname(fileURLToPath(import.meta.url));
const serverDir = resolve(__dirname, "..");
const repoRoot = resolve(serverDir, "..");

const uiBundles = [
  {
    name: "dashboard",
    entry: resolve(serverDir, "ui", "dashboard.mjs"),
    template: resolve(serverDir, "ui", "dashboard.html"),
    outModule: resolve(serverDir, "generated", "dashboard-html.mjs"),
    exportName: "DASHBOARD_HTML",
  },
  {
    name: "task-pane",
    entry: resolve(serverDir, "ui", "task-pane.mjs"),
    template: resolve(serverDir, "ui", "task-pane.html"),
    outModule: resolve(serverDir, "generated", "task-pane-html.mjs"),
    exportName: "TASK_PANE_HTML",
  },
];

const placeholder = "/*__ACP_HUB_UI_JS__*/";

// Mark @modelcontextprotocol/* packages side-effect-free for browser UI bundling
// so unused OAuth/SSE/Cloudflare Worker modules are tree-shaken out of the inline HTML.
const mcpTreeShakePlugin = {
  name: "mcp-browser-treeshake",
  setup(b) {
    b.onResolve({ filter: /.*/ }, async (args) => {
      if (args.pluginData?.skip) return null;
      if (
        !args.path.includes("modelcontextprotocol") &&
        !args.importer.includes("modelcontextprotocol")
      ) {
        return null;
      }
      const resolved = await b.resolve(args.path, {
        importer: args.importer,
        resolveDir: args.resolveDir,
        kind: args.kind,
        pluginData: { skip: true },
      });
      return { ...resolved, sideEffects: false };
    });
  },
};

function minifyInlineCss(html) {
  return html.replace(/<style>([\s\S]*?)<\/style>/i, (_, css) => {
    const compact = css
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/\s+/g, " ")
      .replace(/\s*([{}:;,>+~])\s*/g, "$1")
      .replace(/;}/g, "}")
      .trim();
    return `<style>${compact}</style>`;
  });
}

// Phase 1: Bundle each MCP App UI script and inline it into a self-contained HTML module.
for (const bundle of uiBundles) {
  const uiBuild = await build({
    entryPoints: [bundle.entry],
    bundle: true,
    platform: "browser",
    target: ["es2022"],
    format: "esm",
    minify: true,
    treeShaking: true,
    sourcemap: false,
    write: false,
    legalComments: "none",
    plugins: [mcpTreeShakePlugin],
  });

  const bundledUiJs = uiBuild.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  const templateHtml = minifyInlineCss(readFileSync(bundle.template, "utf8"));
  if (!templateHtml.includes(placeholder)) {
    throw new Error(`UI template ${bundle.template} is missing placeholder ${placeholder}`);
  }
  const finalHtml = templateHtml.replace(placeholder, () => bundledUiJs);

  mkdirSync(dirname(bundle.outModule), { recursive: true });
  writeFileSync(
    bundle.outModule,
    `// Auto-generated by server/scripts/build.mjs — do not edit manually.\nexport const ${bundle.exportName} = ${JSON.stringify(finalHtml)};\n`,
    "utf8",
  );

  const htmlSizeKb = (Buffer.byteLength(finalHtml, "utf8") / 1024).toFixed(1);
  console.log(
    `[build] Generated self-contained MCP App HTML (${bundle.name}): ${bundle.outModule} (${htmlSizeKb} KB)`,
  );
}

// Phase 2: Bundle the MCP server (with all inline UI HTML embedded) into a single file.
const entryPoint = resolve(serverDir, "index.mjs");
const outfile = resolve(repoRoot, "dist", "mcp-server.mjs");

const serverBuild = await build({
  entryPoints: [entryPoint],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  minifyWhitespace: true,
  minifySyntax: true,
  minifyIdentifiers: false,
  treeShaking: true,
  sourcemap: false,
  write: false,
  legalComments: "eof",
  banner: {
    js: [
      'import { createRequire as __acpHubCreateRequire } from "node:module";',
      "const require = __acpHubCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});

mkdirSync(dirname(outfile), { recursive: true });
const tmpOut = `${outfile}.${process.pid}.${Date.now()}.tmp`;
writeFileSync(tmpOut, serverBuild.outputFiles[0].contents);
let lastErr = null;
for (let attempt = 0; attempt < 5; attempt += 1) {
  try {
    renameSync(tmpOut, outfile);
    lastErr = null;
    break;
  } catch (err) {
    lastErr = err;
    await new Promise((r) => setTimeout(r, 80 * (attempt + 1)));
  }
}
if (lastErr) {
  try {
    rmSync(tmpOut, { force: true });
  } catch {
    // ignore cleanup failure
  }
  throw lastErr;
}

const sizeKb = (statSync(outfile).size / 1024).toFixed(1);
console.log(`[build] Generated self-contained MCP bundle: ${outfile} (${sizeKb} KB)`);
